PUBLISH_EXT = (".png", ".jpg", ".jpeg", ".webp")
# CURATION.md's vocabulary, so the two ledgers read alike. KEEP here is a
# *flavour worth keeping*; CURATION.md's KEEP (the final) is PROMOTE.
