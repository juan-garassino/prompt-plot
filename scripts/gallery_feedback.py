"""Juan's judgements on plates, in a form Claude Code agents read and act on.

The viewer's old keep/rework/cut buttons wrote to ``localStorage`` — a store no
agent can see, so looking at 454 plates produced judgements that died in the
browser. This module is the on-disk half.

Two deliberate choices:

* Feedback lives under **tracked** ``studio/``, not under ``gallery/`` which is
  entirely gitignored. A note written into gallery/ would never version and
  would vanish on a clean checkout. ``STUDIO.md`` already declares that every
  piece's artifacts belong in ``studio/<slug>/``, which is also where an agent
  working on that piece looks.
* Every record carries the **piece path**. That is what makes feedback
  actionable rather than merely readable: a note on a render resolves to the
  source file an agent must edit.

Stdlib only, matching ``gallery_index.py`` — the project env does not reliably
resolve, so these tools must run from any interpreter.
"""

from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, List, Optional

