GALLERY = REPO / "gallery"
STUDIO = REPO / "studio"
LOG = STUDIO / "feedback.jsonl"

VERDICTS = ("promote", "rework", "cut")
# CURATION.md's vocabulary, so the two ledgers read alike.
CURATION_EQUIV = {"promote": "KEEP", "rework": "REWORK", "cut": "KILL"}

GENERATED = "Generated by `scripts/gallery_feedback.py` — do not edit by hand."

